// Include support for different sign-in methods, like via Google or socials (displayName will need to be added to UserInfo for that as well as functions in this doc supporting those sign-in options).
import { createUserWithEmailAndPassword, updateProfile, signInWithEmailAndPassword, signOut, sendPasswordResetEmail, verifyPasswordResetCode, confirmPasswordReset, EmailAuthProvider, reauthenticateWithCredential, verifyBeforeUpdateEmail, updatePassword, deleteUser as deleteAuthUser } from 'firebase/auth';
import { doc, getDoc, writeBatch, serverTimestamp } from 'firebase/firestore';
import { auth, db } from '../firebase';
import { docData } from '../utils/timestamps';
import { archiveService } from './archive.service';
import { fitService } from './fit.service';
import type { UserInfo } from '../types';

export const authService = {
    // This is just a simple function that retrieves the current user's info (AKA that user's document).
    async getUserInfo(uid: string): Promise<UserInfo | null> {
        const userDoc = await getDoc(doc(db, "users", uid));
        return userDoc.exists() ? ({ uid: userDoc.id, ...docData(userDoc) } as UserInfo) : null;
    },

    // This function handles user sign-up, promises a UserInfo object.
    async signUp(
        email: string,
        password: string,
        displayName: string,
        username: string
    ): Promise<UserInfo> {
        // Re-checking username availability right before creating the Auth account (the sign-up form already checks, but that could be minutes stale). This minimizes the window where an Auth account gets created and then the Firestore batch below fails, stranding a half-made account.
        // The real uniqueness guarantee is in firestore.rules: username docs can only be CREATED, never overwritten, so if two users race for the same name the loser's whole batch fails atomically.
        if (await this.checkUsernameExists(username)) {
            throw new Error("That username is already taken.");
        }

        const { user } = await createUserWithEmailAndPassword(auth, email, password);

        // Updating the user's profile with displayName param.
        await updateProfile(user, { displayName });

        // Setting up a userInfo object with the values generated by Firebase create user function.
        // Email is deliberately left out since user docs are readable by other users, Firebase Auth already stores it on the account itself.
        // Both counters start at 0, which the security rules require on create.
        const userInfo: Omit<UserInfo, 'uid'> = {
            displayName,
            username: username.toLowerCase(),
            createdAt: new Date().toISOString(), // Only a local stand-in for the returned profile; both docs below get the server's time, which is all the rules accept.
            followerCount: 0,
            followingCount: 0
        };

        // Setting up a batch to handle multiple writes to Firestore in a single atomic operation.
        const batch = writeBatch(db);

        // Setting up a separate document for the "usernames" collection to ensure no duplicate usernames.
        batch.set(doc(db, "usernames", userInfo.username), {
            uid: user.uid,
            username: username.toLowerCase(),
            createdAt: serverTimestamp()
        });

        // Setting up a user doc via userInfo object above and committing the write to Firestore.
        batch.set(doc(db, "users", user.uid), { ...userInfo, createdAt: serverTimestamp() });
        await batch.commit();

        return {
            uid: user.uid,
            ...userInfo
        };
    },

    // This function handles user sign-in. The profile itself isn't read here: the auth context's listener on the user doc loads it, and its status ('noProfile') covers an account without one.
    // (Reading it here too used to throw for a missing profile after the user was already signed in, so the login form showed an error for an account the app considered signed in.)
    async signIn(
        email: string,
        password: string
    ): Promise<void> {
        await signInWithEmailAndPassword(auth, email, password);
    },

    // This function sends Firebase's password reset email (a link to pick a new password) to the given address.
    // With email enumeration protection on (Firebase's default), this succeeds even when no account uses the email, so the login form can show the same message either way.
    // url adds a "Continue" button to Firebase's reset page, which brings the user back to the app's login page once the new password is saved. Its domain has to be on the Authorized domains list in the console (localhost is by default).
    // NOTE: the link itself still opens Firebase's hosted page (handleCodeInApp doesn't skip it for reset emails, tested). Sending it to the app's own /reset-password page needs the console's custom action URL instead (see to-do.txt).
    async resetPassword(email: string): Promise<void> {
        await sendPasswordResetEmail(auth, email, {
            url: `${window.location.origin}/login` // Whatever domain the app is running on, so this works in dev and prod without changes.
        });
    },

    // Checks the code from a reset link (the oobCode in its URL) and returns the email it's for. Throws if the link has expired or was already used.
    // This doesn't use up the code, so the reset page can check it as soon as it opens and only spend it once the new password is submitted.
    async verifyResetCode(code: string): Promise<string> {
        return await verifyPasswordResetCode(auth, code);
    },

    // Sets the new password for the account the reset code belongs to. This is what uses up the code, so the same link can't be used twice.
    async confirmReset(code: string, newPassword: string): Promise<void> {
        await confirmPasswordReset(auth, code, newPassword);
    },

    // This function handles user sign-out.
    async signOut(): Promise<void> {
        await signOut(auth);
    },

    // This function ensures that the user's information in Firestore db is deleted when the user is deleted.
    async deleteUser(uid: string): Promise<void> {
        const userInfo = await this.getUserInfo(uid);

        // If the user does not exist, no need to execute rest of function code.
        if (!userInfo) return;

        const batch = writeBatch(db);

        // Delete user and username docs and commit writes.
        batch.delete(doc(db, "users", uid));
        batch.delete(doc(db, "usernames", userInfo.username));
        await batch.commit();
    },

    // Firebase Auth only allows sensitive changes (email, password, deleting the account) if the user signed in recently, otherwise it throws auth/requires-recent-login.
    // Asking for the current password and re-signing in with it right before the change satisfies that check every time, and doubles as proof that it's really the account owner at the keyboard.
    async reauthenticate(currentPassword: string): Promise<void> {
        const user = auth.currentUser;
        if (!user || !user.email) throw new Error("No signed-in user.");

        const credential = EmailAuthProvider.credential(user.email, currentPassword);
        await reauthenticateWithCredential(user, credential);
    },

    // This function starts an email change. Rather than switching the email right away, verifyBeforeUpdateEmail sends a link to the NEW address and only swaps it once that link is clicked, so a typo can't lock the user out of their account.
    // (The older updateEmail function switches it immediately, but Firebase blocks it on projects with email enumeration protection on, which is the default now.)
    async changeEmail(newEmail: string, currentPassword: string): Promise<void> {
        await this.reauthenticate(currentPassword);
        await verifyBeforeUpdateEmail(auth.currentUser!, newEmail);
    },

    // This function changes the signed-in user's password after confirming the current one.
    async changePassword(currentPassword: string, newPassword: string): Promise<void> {
        await this.reauthenticate(currentPassword);
        await updatePassword(auth.currentUser!, newPassword);
    },

    // This function renames a user. Usernames live in two places (the user doc and its claim doc in "usernames"), so all three writes go in one atomic batch:
    // claim the new name, give up the old one, and point the user doc at the new one. The security rules (users update case #4) only accept the username change as part of this exact batch.
    // Posts and comments still store the old username, but the UI shows each author's live username from their user doc, so they update on their own.
    async changeUsername(uid: string, oldUsername: string, newUsername: string): Promise<void> {
        const username = newUsername.toLowerCase();

        // Same pre-check as signUp. The real guarantee is still the rules: a claim doc can only be created, never overwritten, so if someone grabs the name first this whole batch fails.
        if (await this.checkUsernameExists(username)) {
            throw new Error("That username is already taken.");
        }

        const batch = writeBatch(db);
        batch.set(doc(db, "usernames", username), {
            uid,
            username,
            createdAt: serverTimestamp()
        });
        batch.delete(doc(db, "usernames", oldUsername));
        batch.update(doc(db, "users", uid), { username });
        await batch.commit();
    },

    // This function permanently deletes the signed-in user's account: first their Firestore docs (via deleteUser above), then the Firebase Auth account itself.
    // The order matters, since the Firestore rules need the user to still be signed in to delete their own docs. Re-authenticating first is what keeps the Auth deletion from failing afterwards with requires-recent-login.
    // NOTE: their posts, comments, likes, follow docs, and Storage images are NOT removed here (a client can't clean all of that up safely). That's the account deletion Cloud Function on the to-do list.
    async deleteAccount(currentPassword: string): Promise<void> {
        await this.reauthenticate(currentPassword);

        const user = auth.currentUser!;

        // The style board (archive and fits) is private, so the owner can clear it from here, unlike their posts, comments, and follows (see the NOTE above).
        await archiveService.deleteAll(user.uid);
        await fitService.deleteAll(user.uid);

        await this.deleteUser(user.uid);
        await deleteAuthUser(user);
    },

    // As its name suggests, this function returns a boolean indicating a username's existence in the "usernames" collection.
    async checkUsernameExists(username: string): Promise<boolean> {
        const usernameDoc = await getDoc(doc(db, "usernames", username.toLowerCase()));
        return usernameDoc.exists();
    }
};